-- 短链服务的初始表结构。
--
-- 索引设计理由（详见 README「设计决策」）：
--   * uq_links_code            - 短码唯一性的硬保证，同时是重定向/详情/统计的查询路径
--   * uq_link_daily_visit      - 每个 (链接, 日期) 只有一行聚合；让按天自增只命中单行锁，
--                                并让 7 天范围扫描保持很小
--   * idx_links_created_at     - 支撑分页的「最新链接」列表
--   * links.url 不建索引       - 重复 URL 始终生成新短码，因此 url 从不被查询

CREATE TABLE IF NOT EXISTS links (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    code             VARCHAR(32)   NOT NULL,
    url              VARCHAR(2048) NOT NULL,
    created_at       TIMESTAMP(6)  NOT NULL,
    expires_at       TIMESTAMP(6)  NULL,
    visit_count      BIGINT        NOT NULL DEFAULT 0,
    last_visited_at  TIMESTAMP(6)  NULL,
    CONSTRAINT pk_links PRIMARY KEY (id),
    CONSTRAINT uq_links_code UNIQUE (code)
);

CREATE INDEX IF NOT EXISTS idx_links_created_at ON links (created_at DESC);

CREATE TABLE IF NOT EXISTS link_daily_visit (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    link_id      BIGINT NOT NULL,
    visit_day    DATE   NOT NULL,
    visit_count  BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT pk_link_daily_visit PRIMARY KEY (id),
    CONSTRAINT uq_link_daily_visit UNIQUE (link_id, visit_day),
    CONSTRAINT fk_link_daily_visit_links FOREIGN KEY (link_id) REFERENCES links (id) ON DELETE CASCADE
);
